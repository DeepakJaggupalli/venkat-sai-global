/**
 * "Refer a friend" rewards. Layer 20 — after cv-submissions (a payout belongs to one CV submission).
 *
 * Anyone (a worker or an agent) gets a personal link /r/<CODE> at /refer with their name and mobile number. A person
 * who applies through the link carries the code on their CV submission (cv_submissions.referralCode, upper-case).
 * When that CV reaches status "departed" the referrer's reward is due; staff pay it and record the payout here.
 * The reward status is DERIVED, never stored: departed → due (paid once a payout row exists), not_suitable → not
 * eligible, anything else → in progress (src/modules/referrals/schemas.ts → deriveRewardStatus).
 *
 * Personal data supplied voluntarily to receive the reward (consent on the form, privacy notice version kept).
 * `ipHash` only (never the raw IP).
 */
import { sql } from "drizzle-orm";
import { check, index, pgTable, text, uniqueIndex, uuid } from "drizzle-orm/pg-core";

import { currencyCode, moneyMinor, pk, timestamps, tstz } from "./_shared";
import { users } from "./core";
import { cvSubmissions } from "./cv-submissions";
import { currencies } from "./taxonomy";

export const REFERRER_STATUSES = ["active", "blocked"] as const;
export type ReferrerStatus = (typeof REFERRER_STATUSES)[number];

export const referrers = pgTable(
  "referrers",
  {
    id: pk(),
    /**
     * Share code in /r/<CODE>: 6 characters from an unambiguous alphabet (no 0/O, 1/I), generated by the referrals
     * module. The check allows 4–16 letters/digits, the same as cv_submissions.referralCode.
     */
    code: text().notNull(),
    name: text().notNull(),
    /** E.164 mobile / WhatsApp number: one referrer per number (the reward is paid to this number's owner). */
    phone: text().notNull(),
    /** Optional email, lower-cased and trimmed. */
    email: text(),
    /** blocked = the link stops working and no payout can be recorded (staff use it against abuse). */
    status: text({ enum: REFERRER_STATUSES }).notNull().default("active"),
    statusChangedAt: tstz(),
    statusChangedByUserId: uuid().references(() => users.id, { onDelete: "set null" }),
    /** Version of the privacy notice shown on the /refer form. */
    privacyNoticeVersion: text(),
    ipHash: text(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex("referrers_code_uq").on(t.code),
    uniqueIndex("referrers_phone_uq").on(t.phone),
    index("referrers_status_idx").on(t.status, t.createdAt),
    index("referrers_status_changed_by_idx").on(t.statusChangedByUserId),
    check("referrers_code_chk", sql`${t.code} ~ '^[A-Z0-9]{4,16}$'`),
    check("referrers_name_chk", sql`btrim(${t.name}) <> '' and char_length(${t.name}) <= 120`),
    check("referrers_phone_chk", sql`${t.phone} ~ '^[+][1-9][0-9]{6,14}$'`),
    check("referrers_email_chk", sql`${t.email} is null or (char_length(${t.email}) <= 254 and ${t.email} = lower(${t.email}))`),
  ],
);

/**
 * A reward paid to a referrer for one placed CV submission (at most one per submission). Money is integer minor units
 * with an explicit currency chosen by staff (never assumed). Deleting the CV submission removes its payout record.
 */
export const referralPayouts = pgTable(
  "referral_payouts",
  {
    id: pk(),
    cvSubmissionId: uuid()
      .notNull()
      .references(() => cvSubmissions.id, { onDelete: "cascade" }),
    /** The referrer paid (the owner of the CV's referral code when the payout was recorded). */
    referrerId: uuid()
      .notNull()
      .references(() => referrers.id),
    amountMinor: moneyMinor().notNull(),
    currency: currencyCode()
      .notNull()
      .references(() => currencies.code),
    paidAt: tstz().notNull().defaultNow(),
    paidByUserId: uuid().references(() => users.id, { onDelete: "set null" }),
    /** Staff note, e.g. "Paid by UPI, ref 4521". */
    note: text(),
    ...timestamps,
  },
  (t) => [
    uniqueIndex("referral_payouts_cv_submission_uq").on(t.cvSubmissionId),
    index("referral_payouts_referrer_idx").on(t.referrerId, t.paidAt),
    index("referral_payouts_paid_by_idx").on(t.paidByUserId),
    index("referral_payouts_currency_idx").on(t.currency),
    check("referral_payouts_amount_chk", sql`${t.amountMinor} > 0`),
    check("referral_payouts_note_chk", sql`${t.note} is null or char_length(${t.note}) <= 500`),
  ],
);
