/**
 * LOCAL-ONLY end-to-end test seed: test accounts for every role plus the organisations, jobs, applications,
 * partner assignments / submissions, courses / batches, plans and CMS entries the Playwright specs use.
 *
 *   npm run db:seed:e2e                       # rotates every password, recreates the "fresh" accounts
 *   npm run db:seed:e2e -- --keep-passwords   # keeps persistent accounts' passwords from the env file
 *
 * Refuses to run unless DATABASE_URL points at 127.0.0.1 / localhost and NODE_ENV is not production
 * (src/server/seed/e2e-guard.ts). Run `npm run db:migrate` and `npm run db:seed` first.
 *
 * Writes the accounts and ids to E2E_ENV_FILE (default: ../VenkatSaiGlobal-work/e2e/e2e.env next to the
 * repository) as KEY=value lines for `set -a; . e2e.env; set +a`. The file holds passwords: never commit it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import Module from "node:module";
import path from "node:path";

const root = path.resolve(__dirname, "..");

/** Same alias as scripts/seed.ts: resolve next/navigation to its react-server build outside Next.js. */
function aliasReactServerNavigation(): void {
  const target = require.resolve("next/dist/client/components/navigation.react-server.js");
  const loader = Module as unknown as { _resolveFilename: (request: string, ...rest: unknown[]) => string };
  const original = loader._resolveFilename;
  loader._resolveFilename = function resolve(this: unknown, request: string, ...rest: unknown[]): string {
    if (request === "next/navigation" || request === "next/navigation.js") return target;
    return original.call(this, request, ...rest);
  };
}
aliasReactServerNavigation();

/** Services record server-side analytics after commits; outside a request that is expected to be skipped. */
const originalWarn = console.warn.bind(console);
console.warn = (...args: unknown[]): void => {
  if (typeof args[0] === "string" && args[0].includes("Server-side analytics event was not recorded")) return;
  originalWarn(...args);
};

function redactUrl(url: URL): string {
  return `${url.protocol}//${url.hostname}:${url.port || "5432"}${url.pathname}`;
}

async function main(): Promise<number> {
  const { loadEnvConfig } = await import("@next/env");
  loadEnvConfig(root, process.env.NODE_ENV !== "production", { info: () => undefined, error: console.error });

  const { assertE2eSeedAllowed, formatEnvFile, parseEnvFile, E2eSeedRefused } = await import("@/server/seed/e2e-guard");
  let url: URL;
  try {
    url = assertE2eSeedAllowed(process.env);
  } catch (error) {
    if (error instanceof E2eSeedRefused) {
      console.error(`E2E seed refused: ${error.message}`);
      return 2;
    }
    throw error;
  }

  const envFile = path.resolve(process.env.E2E_ENV_FILE ?? path.join(root, "..", "VenkatSaiGlobal-work", "e2e", "e2e.env"));
  const keepPasswords = process.argv.includes("--keep-passwords");
  const keptPasswords = keepPasswords && existsSync(envFile) ? parseEnvFile(readFileSync(envFile, "utf8")) : {};

  console.log(`E2E seed on ${redactUrl(url)}${keepPasswords ? " (keeping passwords)" : ""}`);
  const started = Date.now();
  // Imported only after the guard: loading @/db opens a pool to DATABASE_URL.
  const { pool } = await import("@/db");
  try {
    const { runE2eSeed } = await import("@/server/seed/e2e");
    const { env } = await runE2eSeed({ keptPasswords, log: (message) => console.log(message) });
    mkdirSync(path.dirname(envFile), { recursive: true });
    writeFileSync(
      envFile,
      formatEnvFile(env, [
        "Venkat Sai Global local E2E accounts and ids — generated by `npm run db:seed:e2e`.",
        "Contains test passwords for the LOCAL database only. Never commit, print or share this file.",
        "Load in bash: set -a; . <this file>; set +a",
      ]),
      { encoding: "utf8", mode: 0o600 },
    );
    console.log(`Wrote ${Object.keys(env).length} variables to ${envFile}`);
  } catch (error) {
    console.error("E2E seed failed:", error instanceof Error ? (error.stack ?? error.message) : error);
    return 1;
  } finally {
    await pool.end().catch(() => undefined);
  }
  console.log(`E2E seed finished in ${((Date.now() - started) / 1000).toFixed(1)} s.`);
  return 0;
}

main()
  .then((code) => {
    process.exitCode = code;
  })
  .catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
