function inPolygon(lon: number, lat: number, poly: readonly LonLat[]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]!;
    const [xj, yj] = poly[j]!;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Evenly spaced points on land (lon, lat), `step` degrees apart along each parallel at the equator. */
export function landDots(step = 2.4): LonLat[] {
  const out: LonLat[] = [];
  for (let lat = -56; lat <= 82; lat += step) {
    const lonStep = step / Math.max(Math.cos((lat * Math.PI) / 180), 0.2);
    for (let lon = -180; lon < 180; lon += lonStep) {
      if (LAND.some((poly) => inPolygon(lon, lat, poly))) out.push([lon, lat]);
    }
  }
  return out;
}
