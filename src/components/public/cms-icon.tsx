export function iconFor(name: string | null | undefined, fallback: LucideIcon = Layers): LucideIcon {
  return (name && (ICONS as Record<string, LucideIcon>)[name]) || fallback;
}

/** Decorative icon for a CMS entry (the entry title always carries the meaning). */
export function CmsIcon({ name, fallback, className }: { name?: string | null; fallback?: LucideIcon; className?: string }) {
  // createElement: the icon is looked up from a static map, not created during render.
  return createElement(iconFor(name, fallback), { "aria-hidden": true, className });
}
